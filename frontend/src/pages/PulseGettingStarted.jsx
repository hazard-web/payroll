function IndustrySelect({ value, onChange, disabled }) {
  const rootRef = useRef(null)
  const searchRef = useRef(null)
  const [open, setOpen] = useState(false)
  const [query, setQuery] = useState('')

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase()
    if (!q) return INDUSTRIES
    return INDUSTRIES.filter((item) => item.toLowerCase().includes(q))
  }, [query])

  useEffect(() => {
    if (!open) return undefined
    const onDoc = (e) => {
      if (!rootRef.current?.contains(e.target)) setOpen(false)
    }
    const onKey = (e) => {
      if (e.key === 'Escape') setOpen(false)
    }
    document.addEventListener('mousedown', onDoc)
    document.addEventListener('keydown', onKey)
    window.setTimeout(() => searchRef.current?.focus(), 0)
    return () => {
      document.removeEventListener('mousedown', onDoc)
      document.removeEventListener('keydown', onKey)
    }
  }, [open])

  const pick = (item) => {
    onChange(item)
    setQuery('')
    setOpen(false)
  }

  return (
    <div className={`pgs-combo${open ? ' is-open' : ''}`} ref={rootRef}>
      <button
        type="button"
        className="pgs-combo-trigger"
        disabled={disabled}
        aria-haspopup="listbox"
        aria-expanded={open}
        onClick={() => {
          if (disabled) return
          setOpen((v) => !v)
          setQuery('')
        }}
      >
        <span className={value ? 'is-value' : 'is-placeholder'}>{value || 'Select'}</span>
        <i className="pgs-combo-chevron" aria-hidden="true" />
      </button>

      {open ? (
        <div className="pgs-combo-menu" role="listbox">
          <div className="pgs-combo-search">
            <svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true">
              <circle cx="11" cy="11" r="7" fill="none" stroke="currentColor" strokeWidth="2" />
              <path
                d="M16.5 16.5L21 21"
                fill="none"
                stroke="currentColor"
                strokeWidth="2"
                strokeLinecap="round"
              />
            </svg>
            <input
              ref={searchRef}
              type="search"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder="Search"
              aria-label="Search industries"
              autoComplete="off"
            />
          </div>
          <ul className="pgs-combo-list">
            {filtered.length === 0 ? (
              <li className="pgs-combo-empty">No matches</li>
            ) : (
              filtered.map((item) => (
                <li key={item}>
                  <button
                    type="button"
                    role="option"
                    aria-selected={item === value}
                    className={item === value ? 'is-active' : undefined}
                    onClick={() => pick(item)}
                  >
                    {item}
                  </button>
                </li>
              ))
            )}
          </ul>
        </div>
      ) : null}

      <input
        type="text"
        value={value}
        required
        tabIndex={-1}
        readOnly
        aria-hidden="true"
        className="pgs-combo-ghost"
      />
    </div>
  )
}

